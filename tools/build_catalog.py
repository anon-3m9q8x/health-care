def calc(comps):
    tot = [0.0]*6
    for key, g in comps:
        v = ING[key]
        for i in range(6):
            tot[i] += v[i]*g/100
    kcal, p, f, c, s, fi = tot
    return dict(kcal=round(kcal), protein=round(p,1), fat=round(f,1), carbs=round(c,1), salt=round(s,1), fiber=round(fi,1))

def parse(spec):
    out = []
    for part in spec.split(','):
        k, g = part.strip().split(':')
        out.append((k, float(g)))
    return out

